#!/usr/bin/env python3
"""Builds web/main.c: every header and source of the project merged into one
file, for the wokwi.com ESP-IDF online editor (which compiles one main.c).

Usage (from the repository root):  python3 scripts/make_web_bundle.py
The modular sources in components/ and include/ stay the master copy;
re-run this script after every change.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADERS = [
    "common/config.h", "common/system.h", "comms/bus.h", "auth/runtime.h",
    "storage/runtime.h", "actuator/runtime.h", "rooms/core.h", "rooms/runtime.h",
    "entrance/core.h", "entrance/kpmenu.h", "entrance/mfrc522.h", "entrance/display.h",
    "entrance/clock.h", "entrance/dashboard.h", "entrance/runtime.h", "cli/runtime.h",
]
SOURCES = [
    "components/common/system.c", "components/comms/bus.c", "components/auth/session.c",
    "components/auth/runtime.c", "components/storage/runtime.c", "components/actuator/runtime.c",
    "components/rooms/core.c", "components/rooms/runtime.c", "components/entrance/core.c",
    "components/entrance/kpmenu.c", "components/entrance/mfrc522.c", "components/entrance/display.c",
    "components/entrance/clock.c", "components/entrance/dashboard.c", "components/entrance/runtime.c",
    "components/cli/runtime.c", "src/main.c",
]
LOCAL = re.compile(r'^\s*#\s*include\s+"([^"]+)"')

def body(path):
    out = []
    for line in open(os.path.join(ROOT, path), encoding="utf-8"):
        m = LOCAL.match(line)
        if m and os.path.exists(os.path.join(ROOT, "include", m.group(1))):
            continue  # project header: already pasted above
        out.append(line)
    return "".join(out)

def main():
    parts = [
        "/*\n * CoCIS Smart Control and Monitoring System - single-file build for wokwi.com\n"
        " * GENERATED by scripts/make_web_bundle.py from include/ and components/.\n"
        " * Do not edit here: edit the modular sources and regenerate.\n */\n"
        '#pragma GCC diagnostic ignored "-Wformat-truncation"\n',
    ]
    for h in HEADERS:
        parts.append(f"\n/* ==== include/{h} ==== */\n" + body(os.path.join("include", h)))
    for s in SOURCES:
        parts.append(f"\n/* ==== {s} ==== */\n" + body(s))
    os.makedirs(os.path.join(ROOT, "web"), exist_ok=True)
    out = os.path.join(ROOT, "web", "main.c")
    open(out, "w", encoding="utf-8").write("".join(parts))
    print(f"wrote {out}")

if __name__ == "__main__":
    sys.exit(main())
